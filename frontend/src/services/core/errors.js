const hasCyrillic = (text) => typeof text === 'string' && /[а-яё]/i.test(text)

/** Первая ошибка валидации: она точнее общего «Проверьте данные (и ещё 2 ошибки)». */
function firstFieldError(errors) {
    if (!errors || typeof errors !== 'object') return null

    for (const list of Object.values(errors)) {
        const text = Array.isArray(list) ? list[0] : list

        if (hasCyrillic(text)) return text
    }

    return null
}

/**
 * Общая ошибка формы — без повтора того, что уже написано под полем.
 *
 * Сообщение ответа 422 совпадает с первой ошибкой валидации. Если форма
 * показывает её под полем, то же самое внизу формы — лишний дубль.
 *
 * @param {object} error ошибка из api.js
 * @param {string[]} shownFields поля, под которыми форма выводит ошибки
 * @param {string} fallback текст, если у ошибки нет своего
 */
export function formError(error, shownFields, fallback) {
    const message = error?.message || fallback
    const underField = shownFields.some((field) => error?.errors?.[field]?.[0] === message)

    return underField ? '' : message
}

/**
 * Сообщение об ошибке по коду ответа и телу.
 *
 * @param {number} status код ответа
 * @param {object} data разобранное тело ответа (может быть пустым)
 */
export function humanError(status, data = {}) {
    if (status === 422) {
        const field = firstFieldError(data.errors)

        if (field) return field
    }

    // Ошибки сервера не пересказываем: в них бывают внутренности (SQL, пути)
    if (status < 500 && hasCyrillic(data.message)) return data.message

    return BY_STATUS[status]
        ?? (status >= 500 ? BY_STATUS[500] : 'Не получилось выполнить действие. Попробуйте ещё раз.')
}
